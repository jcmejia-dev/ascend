export type Case = {
  unchanged?: boolean;
  args: unknown[];
  expected: unknown;
  label: string;
  hidden?: boolean;
};
export type Lesson = {
  id: string;
  title: string;
  tier: "Beginner" | "Intermediate" | "Advanced";
  topic: string;
  prerequisites: string[];
  objective: string;
  explanation: string;
  example: string;
  task: string;
  starter: string;
  hints: string[];
  solution: string;
  cases: Case[];
  checkpoint: string;
  answer: string;
  minutes: number;
};
function lesson(
  id: string,
  title: string,
  tier: Lesson["tier"],
  prerequisites: string[],
  explanation: string,
  example: string,
  task: string,
  solution: string,
  inputs: [unknown[], unknown][],
  checkpoint: string,
  answer: string,
  hints: string[],
): Lesson {
  return {
    id,
    title,
    tier,
    topic: id,
    prerequisites,
    objective: task,
    explanation,
    example,
    task,
    solution,
    starter: "function solve(input) {\n  // Write your solution here.\n}\n",
    hints,
    cases: inputs.map(([args, expected], i) => ({
      args,
      expected,
      label: i ? `Edge case ${i}` : "Example",
      hidden: i > 1,
    })),
    checkpoint,
    answer,
    minutes: tier === "Beginner" ? 20 : tier === "Intermediate" ? 30 : 40,
  };
}
